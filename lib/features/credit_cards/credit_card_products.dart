CreditCardProduct? creditCardProduct(String? id) {
  for (final p in creditCardProducts) { if (p.id == id) { return p; } }
  return null;
}

CreditCardProduct? creditCardVisual(Map<String, dynamic> card, String bank) {
  final id = card['card_product']?.toString() ?? 'standard';
  if (id != 'standard') {
    final product = creditCardProduct(id);
    return product?.bank == bank ? product : null;
  }
  final network = card['network']?.toString().trim().toLowerCase() ?? '';
  final tier = card['card_tier']?.toString() ?? 'unspecified';
  for (final product in creditCardProducts) {
    if (product.standard && product.bank == bank && product.network == network && product.tier == tier) {
      return product;
    }
  }
  return null;
}

class CreditCardProductField extends StatelessWidget {
  const CreditCardProductField({super.key, required this.bank, required this.value, required this.onChanged});
  final String bank, value;
  final ValueChanged<String> onChanged;
  @override
  Widget build(BuildContext context) {
    final options = creditCardProducts.where((p) => p.bank == bank).toList();
    final selected = options.any((p) => p.id == value) ? value : 'standard';
    return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
      DropdownButtonFormField<String>(key: ValueKey('product-$bank-$selected'),
        initialValue: selected, isExpanded: true,
        decoration: const InputDecoration(labelText: 'Producto / diseño físico', prefixIcon: Icon(Icons.style_outlined)),
        items: [const DropdownMenuItem(value: 'standard', child: Text('Según marca y categoría / otro producto')),
          ...options.map((p) => DropdownMenuItem(value: p.id,
            child: Text(p.label, overflow: TextOverflow.ellipsis)))],
        onChanged: (v) { if (v != null) { onChanged(v); } }),
      const SizedBox(height: 8),
      Text(options.isEmpty
        ? 'Para este banco se conserva el diseño general. Selecciona marca y categoría.'
        : 'Elige el producto que coincide con tu tarjeta. La marca y categoría se completan según el diseño elegido.',
        style: const TextStyle(color: Color(0xFF64748B), fontSize: 12, height: 1.4)),
    ]);
  }
}
